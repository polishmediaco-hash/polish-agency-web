class PolishI18n {
  constructor() {
    this.currentLang = this.detectLanguage();
    this.init();
  }

  detectLanguage() {
    const urlParams = new URLSearchParams(window.location.search);
    const paramLang = urlParams.get('lang');
    if (paramLang && (paramLang === 'fr' || paramLang === 'en')) {
      localStorage.setItem('polish_lang', paramLang);
      return paramLang;
    }

    const saved = localStorage.getItem('polish_lang');
    if (saved && (saved === 'fr' || saved === 'en')) {
      return saved;
    }

    const browserLang = (navigator.language || navigator.userLanguage || '').toLowerCase();
    if (browserLang.startsWith('fr')) {
      return 'fr';
    }

    return 'en';
  }

  init() {
    document.addEventListener('DOMContentLoaded', () => {
      this.renderLanguageToggles();
      this.applyLanguage(this.currentLang);
    });
  }

  renderLanguageToggles() {
    const containers = document.querySelectorAll('.lang-toggle-slot');
    containers.forEach(slot => {
      slot.innerHTML = `
        <div class="lang-toggle" role="group" aria-label="Language Selector">
          <button type="button" class="lang-btn ${this.currentLang === 'en' ? 'active' : ''}" onclick="window.polishI18n.setLanguage('en')">EN</button>
          <span class="lang-sep">|</span>
          <button type="button" class="lang-btn ${this.currentLang === 'fr' ? 'active' : ''}" onclick="window.polishI18n.setLanguage('fr')">FR</button>
        </div>
      `;
    });
  }

  setLanguage(lang) {
    if (lang !== 'en' && lang !== 'fr') return;
    this.currentLang = lang;
    localStorage.setItem('polish_lang', lang);
    this.applyLanguage(lang);

    document.querySelectorAll('.lang-btn').forEach(btn => {
      if (btn.textContent.trim().toUpperCase() === lang.toUpperCase()) {
        btn.classList.add('active');
      } else {
        btn.classList.remove('active');
      }
    });

    window.dispatchEvent(new CustomEvent('polishLanguageChanged', { detail: { lang } }));
  }

  applyLanguage(lang) {
    document.documentElement.lang = lang;
    const dict = POLISH_TRANSLATIONS[lang] || POLISH_TRANSLATIONS.en;

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.innerHTML = dict[key];
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.placeholder = dict[key];
      }
    });

    if (dict['apply.title'] && window.location.pathname.includes('/apply')) {
      document.title = dict['apply.title'];
    } else if (dict['creators.title'] && window.location.pathname.includes('/creators')) {
      document.title = dict['creators.title'];
    }
  }

  t(key) {
    const dict = POLISH_TRANSLATIONS[this.currentLang] || POLISH_TRANSLATIONS.en;
    return dict[key] || key;
  }
}

window.POLISH_TRANSLATIONS = POLISH_TRANSLATIONS;
window.polishI18n = new PolishI18n();
